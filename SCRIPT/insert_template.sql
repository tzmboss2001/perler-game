-- =====================================================
-- 拼豆工坊 - 模板插入脚本
-- =====================================================
-- 使用方法：
-- 1. 替换下面的示例数据为你的实际数据
-- 2. 在 phpMyAdmin 或 MySQL 命令行中执行
-- =====================================================

USE perler_beads;

-- =====================================================
-- 示例：插入一个精选模板
-- =====================================================

INSERT INTO templates (
  name,              -- 模板名称
  category_id,       -- 分类ID (1=卡通动漫, 2=游戏角色, 3=可爱动物, 4=风景, 5=节日主题, 6=其他)
  thumbnail_url,     -- 缩略图URL (上传到腾讯云COS后的地址)
  bead_data,         -- 珠子数据 (JSON格式)
  grid_width,        -- 网格宽度
  grid_height,       -- 网格高度
  bead_count,        -- 珠子总数
  color_count,       -- 颜色种类数
  difficulty,        -- 难度 (easy/medium/hard)
  is_featured,       -- 是否精选 (0=否, 1=是)
  sort_order,        -- 排序 (数字越小越靠前)
  use_count,         -- 使用次数 (初始为0)
  status,            -- 状态 (0=禁用, 1=启用)
  created_at,
  updated_at
) VALUES (
  '示例作品名称',                                    -- name
  1,                                                -- category_id: 卡通动漫
  'https://your-cos-url.com/template1.png',        -- thumbnail_url
  '{"beads":[]}',                                   -- bead_data: JSON格式的珠子数据
  16,                                               -- grid_width
  16,                                               -- grid_height
  180,                                              -- bead_count
  4,                                                -- color_count
  'easy',                                           -- difficulty
  1,                                                -- is_featured: 是
  1,                                                -- sort_order
  0,                                                -- use_count
  1,                                                -- status: 启用
  NOW(),
  NOW()
);

-- =====================================================
-- 分类ID对照表：
-- =====================================================
-- 1 = 卡通动漫
-- 2 = 游戏角色
-- 3 = 可爱动物
-- 4 = 风景
-- 5 = 节日主题
-- 6 = 其他
-- =====================================================

-- =====================================================
-- 难度对照：
-- =====================================================
-- easy   = 简单 (适合初学者，通常16x16以下)
-- medium = 中等 (有一定难度，20x20左右)
-- hard   = 困难 (复杂图案，29x29或以上)
-- =====================================================

-- =====================================================
-- bead_data JSON 格式说明：
-- =====================================================
-- {
--   "beads": [
--     {"x": 0, "y": 0, "color": "#ff6b7a"},
--     {"x": 1, "y": 0, "color": "#ffe066"},
--     ...
--   ]
-- }
--
-- 或者简化格式（二维数组）：
-- {
--   "pattern": [
--     ["#ff6b7a", "#ffe066", null, ...],
--     [null, "#ff6b7a", "#ffe066", ...],
--     ...
--   ]
-- }
-- =====================================================

-- =====================================================
-- 查看现有分类
-- =====================================================
SELECT id, name, template_count FROM template_categories ORDER BY sort_order;

-- =====================================================
-- 查看现有模板
-- =====================================================
SELECT id, name, category_id, difficulty, is_featured, use_count FROM templates ORDER BY sort_order;

-- =====================================================
-- 更新分类的模板数量（插入模板后执行）
-- =====================================================
UPDATE template_categories tc
SET template_count = (
  SELECT COUNT(*)
  FROM templates t
  WHERE t.category_id = tc.id AND t.status = 1
);
